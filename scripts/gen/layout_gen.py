#!/usr/bin/env python3
"""Taffy XML layout fixtures (Chrome-generated expectations) -> vectors/ui/layout/*.tsv
and tests/ui/layout_checks_*.rce. Usage: layout_gen.py TAFFY_DIR"""
import sys, os, glob, xml.etree.ElementTree as ET
sys.path.insert(0, os.path.dirname(__file__))
from rcelit import lit
root = os.path.join(os.path.dirname(__file__), '..', '..')
T = sys.argv[1]
def enc_in(e, d, out):
    props = ';'.join('%s=%s' % kv for kv in e.attrib.items())
    if e.tag == 'text':
        txt = ' '.join((e.text or '').split()).replace('\u200b', '|')
        out.append('%d:t;%s#%s' % (d, props, txt))
    else:
        out.append('%d:d;%s' % (d, props))
    for c in e: enc_in(c, d + 1, out)
def enc_ex(e, out):
    a = e.attrib
    s = '%s %s %s %s' % (a['x'], a['y'], a['width'], a['height'])
    if 'scroll_width' in a: s += ' s%s,%s' % (a['scroll_width'], a['scroll_height'])
    if 'resolved-rows' in a: s += ' r[%s] c[%s]' % (a['resolved-rows'], a['resolved-columns'])
    out.append(s)
    for c in e: enc_ex(c, out)
rows = []
for f in sorted(glob.glob(os.path.join(T, 'tests/xml/*/*.xml'))):
    cat = os.path.basename(os.path.dirname(f))
    r = ET.parse(f).getroot()
    v = r.find('viewport')
    i = []; [enc_in(c, 0, i) for c in r.find('input')]
    x = []; [enc_ex(c, x) for c in r.find('expectations')]
    rows.append((cat, r.get('name'), v.get('width') + ' ' + v.get('height'), r.get('use-rounding'), '/'.join(i), ';'.join(x)))
cats = sorted({r[0] for r in rows})
for c in cats:
    with open(os.path.join(root, 'vectors/ui/layout/%s.tsv' % c), 'w') as o:
        for r in rows:
            if r[0] == c: o.write('\t'.join(r[1:]) + '\n')
for old in glob.glob(os.path.join(root, 'tests/ui/layout_checks_*.rce')): os.remove(old)
N = 40
for k in range(0, len(rows), N):
    with open(os.path.join(root, 'tests/ui/layout_checks_%03d.rce' % (k // N)), 'w') as o:
        o.write('# generated by scripts/gen/layout_gen.py; do not edit\n')
        for r in rows[k:k + N]:
            o.write('# %s/%s\ncheck lay(%s, %s, %s) == %s\n' % (r[0], r[1], lit(r[2]), lit(r[3]), lit(r[4]), lit(r[5])))
print(len(rows), 'vectors', (len(rows) + N - 1) // N, 'shards')
